import React, { useState, useEffect } from "react";
import { useApp } from "../../context/AppContext";
import { PROJECT_TEMPLATES, PRESET_TAGS, METHODOLOGIES, todayISO, addDays } from "../../constants/seedMeta";
import { Modal, TagChip } from "../ui/Primitives";

export function ProjectModal() {
  const {
    projectModalState,
    setProjectModalState,
    users,
    createProject,
    updateProject,
    updateProjectStatus,
    addProjectMember,
    removeProjectMember,
    showToast,
    navigate,
    refreshUsers,
  } = useApp();

  const { open, editProject } = projectModalState;

  const [name, setName] = useState("");
  const [description, setDescription] = useState("");
  const [template, setTemplate] = useState("Web App");
  const [methodology, setMethodology] = useState("Agile");
  const [status, setStatus] = useState("Active");
  const [startDate, setStartDate] = useState(todayISO());
  const [endDate, setEndDate] = useState(addDays(todayISO(), 30));
  const [memberIds, setMemberIds] = useState([]);
  const [tags, setTags] = useState([]);
  const [customTag, setCustomTag] = useState("");
  const [error, setError] = useState("");
  const [submitting, setSubmitting] = useState(false);

  useEffect(() => {
    if (!open) return;
    setError("");
    refreshUsers(); // pick up employees added or onboarded since sign-in
    if (editProject) {
      setName(editProject.name || "");
      setDescription(editProject.description || "");
      setTemplate(editProject.template || "Blank");
      setMethodology(editProject.methodology || "Agile");
      setStatus(editProject.status || "Active");
      setStartDate(editProject.startDate || todayISO());
      setEndDate(editProject.endDate || addDays(todayISO(), 30));
      setMemberIds(editProject.memberIds || []);
      setTags(editProject.tags || []);
    } else {
      const start = todayISO();
      setName("");
      setDescription("");
      setTemplate("Web App");
      setMethodology("Agile");
      setStatus("Active");
      setStartDate(start);
      setEndDate(addDays(start, 30));
      setMemberIds([]); // the server adds the creating PM
      setTags(PROJECT_TEMPLATES["Web App"].tags);
    }
  }, [open, editProject, refreshUsers]);

  const teamMembers = users.filter((u) => u.role === "Team Member");

  const handleTemplateChange = (newTpl) => {
    setTemplate(newTpl);
    if (!editProject && PROJECT_TEMPLATES[newTpl]) {
      setTags(PROJECT_TEMPLATES[newTpl].tags);
    }
  };

  const toggleMember = (userId) => {
    setMemberIds((prev) =>
      prev.includes(userId) ? prev.filter((id) => id !== userId) : [...prev, userId]
    );
  };

  const toggleTag = (tag) => {
    setTags((prev) => (prev.includes(tag) ? prev.filter((t) => t !== tag) : [...prev, tag]));
  };

  const addCustomTag = () => {
    const t = customTag.trim();
    if (t && !tags.includes(t)) {
      setTags((prev) => [...prev, t]);
    }
    setCustomTag("");
  };

  const handleClose = () => {
    setProjectModalState({ open: false, editProject: null });
  };

  const handleSubmit = async (e) => {
    e.preventDefault();
    setError("");
    if (!name.trim()) {
      setError("Project name is required.");
      return;
    }
    if (endDate < startDate) {
      setError("End date cannot be earlier than start date.");
      return;
    }

    setSubmitting(true);
    try {
      if (editProject) {
        // Details, status and team each have their own endpoint
        const updated = await updateProject(
          editProject.id,
          { name: name.trim(), description: description.trim(), template, startDate, endDate, tags },
          { quiet: true }
        );
        if (!updated) return;
        if (status !== editProject.status && !(await updateProjectStatus(editProject.id, status))) return;
        const before = editProject.memberIds || [];
        for (const userId of memberIds.filter((id) => !before.includes(id))) {
          if (!(await addProjectMember(editProject.id, userId, { quiet: true }))) return;
        }
        for (const userId of before.filter((id) => !memberIds.includes(id))) {
          if (!(await removeProjectMember(editProject.id, userId, { quiet: true }))) return;
        }
        showToast("Project updated", "success");
      } else {
        const tplConfig = PROJECT_TEMPLATES[template] || PROJECT_TEMPLATES.Blank;
        const created = await createProject({
          name: name.trim(),
          description: description.trim() || tplConfig.description,
          template,
          methodology,
          status,
          startDate,
          endDate,
          memberIds,
          tags,
          milestones: tplConfig.buildMilestones(startDate),
          // Template sprints are Agile; Waterfall phases and Iterative cycles are generated by the server
          sprints: methodology === "Agile" ? tplConfig.buildSprints(startDate) : [],
        });
        if (!created) return;
        navigate("project-detail", created.id, "overview");
      }
      handleClose();
    } finally {
      setSubmitting(false);
    }
  };

  return (
    <Modal
      open={open}
      onClose={handleClose}
      title={editProject ? `Edit Project — ${editProject.name}` : "Create New Project"}
      width="640px"
    >
      <form onSubmit={handleSubmit}>
        {error && (
          <div
            style={{
              padding: "10px 12px",
              borderRadius: 6,
              backgroundColor: "var(--danger-soft)",
              color: "var(--danger)",
              marginBottom: 12,
              fontSize: 12.5,
            }}
          >
            {error}
          </div>
        )}

        <div className="form-group">
          <label className="form-label">Project Name *</label>
          <input
            type="text"
            className="form-input"
            placeholder="e.g. NextGen Customer Portal"
            value={name}
            onChange={(e) => setName(e.target.value)}
            required
          />
        </div>

        <div className="form-row">
          <div className="form-group">
            <label className="form-label">Project Template</label>
            <select
              className="form-select"
              value={template}
              onChange={(e) => handleTemplateChange(e.target.value)}
            >
              {Object.keys(PROJECT_TEMPLATES).map((tplKey) => (
                <option key={tplKey} value={tplKey}>
                  {tplKey}
                </option>
              ))}
            </select>
            {!editProject && PROJECT_TEMPLATES[template] && (
              <span style={{ fontSize: 11.5, color: "var(--text-muted)" }}>
                {PROJECT_TEMPLATES[template].description}
              </span>
            )}
          </div>

          <div className="form-group">
            <label className="form-label">Status</label>
            <select
              className="form-select"
              value={status}
              onChange={(e) => setStatus(e.target.value)}
            >
              <option value="Active">Active</option>
              <option value="Completed">Completed</option>
              <option value="Archived">Archived</option>
            </select>
          </div>
        </div>

        <div className="form-group">
          <label className="form-label">Development Model</label>
          <select
            className="form-select"
            value={methodology}
            onChange={(e) => setMethodology(e.target.value)}
            disabled={Boolean(editProject)}
          >
            {Object.keys(METHODOLOGIES).map((m) => (
              <option key={m} value={m}>
                {m}
              </option>
            ))}
          </select>
          <span style={{ fontSize: 11.5, color: "var(--text-muted)" }}>
            {METHODOLOGIES[methodology].description}
            {editProject && " The model is fixed once a project is created."}
          </span>
        </div>

        <div className="form-group">
          <label className="form-label">Description</label>
          <textarea
            className="form-textarea"
            rows={3}
            placeholder="Describe project scope, deliverables, and objectives..."
            value={description}
            onChange={(e) => setDescription(e.target.value)}
          />
        </div>

        <div className="form-row">
          <div className="form-group">
            <label className="form-label">Start Date *</label>
            <input
              type="date"
              className="form-input"
              value={startDate}
              onChange={(e) => setStartDate(e.target.value)}
              required
            />
          </div>

          <div className="form-group">
            <label className="form-label">Target End Date *</label>
            <input
              type="date"
              className="form-input"
              value={endDate}
              onChange={(e) => setEndDate(e.target.value)}
              required
            />
          </div>
        </div>

        <div className="form-group">
          <label className="form-label">Assign Team Members</label>
          <div
            style={{
              display: "grid",
              gridTemplateColumns: "repeat(auto-fill, minmax(180px, 1fr))",
              gap: 8,
              padding: 10,
              borderRadius: 8,
              border: "1px solid var(--border-color)",
              backgroundColor: "var(--bg-subtle)",
              maxHeight: 150,
              overflowY: "auto",
            }}
          >
            {teamMembers.length === 0 && (
              <span style={{ fontSize: 12.5, color: "var(--text-muted)" }}>
                No active Team Members yet. You can create the project now and add members later.
              </span>
            )}
            {teamMembers.map((u) => (
              <label
                key={u.id}
                style={{
                  display: "flex",
                  alignItems: "center",
                  gap: 8,
                  fontSize: 12.5,
                  cursor: "pointer",
                }}
              >
                <input
                  type="checkbox"
                  checked={memberIds.includes(u.id)}
                  onChange={() => toggleMember(u.id)}
                />
                <span>
                  {u.name} <small style={{ color: "var(--text-muted)" }}>({u.role})</small>
                </span>
              </label>
            ))}
          </div>
        </div>

        <div className="form-group">
          <label className="form-label">Labels / Tags</label>
          <div style={{ display: "flex", flexWrap: "wrap", gap: 6, marginBottom: 8 }}>
            {PRESET_TAGS.map((t) => (
              <button
                key={t}
                type="button"
                className={`btn btn-sm ${tags.includes(t) ? "btn-primary" : "btn-secondary"}`}
                onClick={() => toggleTag(t)}
              >
                #{t}
              </button>
            ))}
          </div>
          <div style={{ display: "flex", gap: 8 }}>
            <input
              type="text"
              className="form-input"
              placeholder="Add custom tag..."
              value={customTag}
              onChange={(e) => setCustomTag(e.target.value)}
              onKeyDown={(e) => {
                if (e.key === "Enter") {
                  e.preventDefault();
                  addCustomTag();
                }
              }}
            />
            <button type="button" className="btn btn-secondary" onClick={addCustomTag}>
              Add Tag
            </button>
          </div>
          {tags.length > 0 && (
            <div style={{ display: "flex", flexWrap: "wrap", gap: 6, marginTop: 8 }}>
              {tags.map((t) => (
                <TagChip key={t} tag={t} onRemove={toggleTag} />
              ))}
            </div>
          )}
        </div>

        <div style={{ display: "flex", justifyContent: "flex-end", gap: 10, marginTop: 18 }}>
          <button type="button" className="btn btn-secondary" onClick={handleClose}>
            Cancel
          </button>
          <button type="submit" className="btn btn-primary" disabled={submitting}>
            {submitting
              ? "Saving..."
              : editProject
              ? "Save Changes"
              : "Create Project"}
          </button>
        </div>
      </form>
    </Modal>
  );
}
